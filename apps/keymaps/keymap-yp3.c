const struct button_mapping *get_context_mapping(int context)
{
    switch (context & ~CONTEXT_LOCKED) {
    case CONTEXT_WPS: return wps;
    case CONTEXT_SETTINGS: return settings;
    case CONTEXT_YESNOSCREEN: return yesno;
    case CONTEXT_TREE:
    case CONTEXT_LIST:
    case CONTEXT_MAINMENU: return lists;
    case CONTEXT_KEYBOARD: return keyboard;
    case CONTEXT_SETTINGS_TIME: return settime;
#ifdef HAVE_PITCHCONTROL
    case CONTEXT_PITCHSCREEN: return pitchscreen;
#endif
    case CONTEXT_SETTINGS_EQ:
    case CONTEXT_SETTINGS_COLOURCHOOSER:
    case CONTEXT_SETTINGS_RECTRIGGER: return values;
#if CONFIG_TUNER
    case CONTEXT_FM: return fm;
#endif
#ifdef HAVE_RECORDING
    case CONTEXT_RECSCREEN: return recscreen;
#endif
    default: return standard;
    }
}
