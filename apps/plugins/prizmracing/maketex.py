#!/usr/bin/env python3
"""Regenerates pr_data.h from PRIZM Racing's art: the three meshes of
src/models.h and resources/textures/car.png (shrunk to 128x128, 32 colour
palette).  Usage:
  maketex.py PRIZM_RACING_CHECKOUT > pr_data.h
Mesh vertices are 4.12 fixed point, normals signed bytes, UVs 4.12."""
import math, re, sys
from PIL import Image

root = sys.argv[1]
src = open(root + '/src/models.h').read()
TEX = 128
PAL = 32

def q12(v, lo=-8.0, hi=7.999):
    return int(round(max(lo, min(hi, v)) * 4096))

def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

out = ['/* Generated by maketex.py from PRIZM Racing (MIT, (c) 2022 Duarte Coelho). */',
       '#define PR_TEX %d' % TEX, '#define PR_PAL %d' % PAL, '']

for name in ('car', 'cone', 'sun'):
    m = re.search(name + r'_triangles\[(\d+)\] = \{(.*?)\n\};', src, re.S)
    n = int(m.group(1))
    body = m.group(2)
    tris = re.findall(r'\{\s*\{\s*(\{[^}]*\},\s*\{[^}]*\},\s*\{[^}]*\}),\s*\}\s*,\s*'
                      r'\{([^}]*)\},\s*newColor\((\d+), (\d+), (\d+)\),\s*\{(.*?)\}\s*\}\s*,', body, re.S)
    assert len(tris) == n, (name, len(tris), n)
    out.append('static const struct pr_tri pr_%s_tris[%d] = {' % (name, n))
    for pts, nrm, r, g, b, uv in tris:
        p = [float(x) for x in re.findall(r'-?\d+\.\d+', pts)]
        nn = [float(x) for x in re.findall(r'-?\d+\.\d+', nrm)]
        u = [float(x) for x in re.findall(r'-?\d+\.\d+', uv)]
        assert len(p) == 9 and len(nn) == 3 and len(u) == 6
        out.append('  {{%s}, {%s}, 0x%04x, {%s}},' % (
            ','.join(str(q12(x)) for x in p),
            ','.join(str(int(round(max(-1, min(1, x)) * 127))) for x in nn),
            rgb565(int(r), int(g), int(b)),
            ','.join(str(q12(x)) for x in u)))
    out.append('};')
    out.append('#define PR_%s_N %d' % (name.upper(), n))
    out.append('')

img = Image.open(root + '/resources/textures/car.png').convert('RGBA')
bg = Image.new('RGBA', img.size, (0, 0, 0, 255))
img = Image.alpha_composite(bg, img).convert('RGB').resize((TEX, TEX), Image.LANCZOS)
q = img.quantize(PAL, method=Image.MEDIANCUT, dither=Image.NONE)
pal = q.getpalette()[:PAL * 3]
pal += [0] * (PAL * 3 - len(pal))
out.append('static const unsigned short pr_palette[PR_PAL] = {')
out.append('  ' + ','.join('0x%04x' % rgb565(*pal[i*3:i*3+3]) for i in range(PAL)))
out.append('};')
out.append('static const unsigned char pr_texture[PR_TEX * PR_TEX] = {')
px = list(q.tobytes())
for y in range(TEX):
    out.append('  ' + ','.join(str(v) for v in px[y*TEX:(y+1)*TEX]) + ',')
out.append('};')
out.append('')
out.append('/* sin(2*pi*i/4096) * 65536 for i = 0..1024 (first quarter wave). */')
out.append('static const int pr_sintab[1025] = {')
vals = [int(round(math.sin(2 * math.pi * i / 4096) * 65536)) for i in range(1025)]
for i in range(0, 1025, 16):
    out.append('  ' + ','.join(str(v) for v in vals[i:i+16]) + ',')
out.append('};')
print('\n'.join(out))
