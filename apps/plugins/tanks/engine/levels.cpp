tile_t tile_from_char(char c)
{
    switch (c) {
    case '#': return 1 | BLOCK;
    case 'o': return 1 | DESTRUCTIBLE;
    case 'h': return HOLE;
    default: return 0;
    }
}

int tank_from_char(char c)
{
    if (c == 'P')
        return PLAYER;
    if (c >= '1' && c <= '9')
        return c - '0';
    return -1;
}
