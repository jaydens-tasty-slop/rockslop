#!/usr/bin/env python3
"""Converts Terrario's art (assets-fx/ of https://github.com/KBD2/terrario)
into the files the Rockbox port uses:
  terrario.dat   packed sprite sheets (loaded from the card on demand)
  tr_images.c    one bopti_image_t per sheet (size, offset in terrario.dat)
  tr_font.c      the 5x6 "smalltext" font
Usage: maketex.py TERRARIO_CHECKOUT OUTDIR
Each sheet is stored as a 2 bit grey plane (0 white, 1 light, 2 dark, 3 black,
4 pixels per byte, LSB first) followed, if the sheet has transparent pixels,
by a 1 bit mask plane (1 = transparent, 8 pixels per byte, LSB first). The
sprite sheet layout (1 px separators) is kept as is: the game indexes it."""
import glob, os, sys
from PIL import Image

root, out = sys.argv[1], sys.argv[2]
SKIP = {'img_confetti', 'img_mainmenu', 'img_splash', 'img_tiles_TEMPLATE', 'img_ui_abouttabs',
        'img_ui_arrowsall', 'img_ui_arrowshoriz', 'img_ui_mainmenuselect', 'img_ui_quit'}

def level(p):
    r, g, b, a = p
    if a < 128:
        return None
    l = (r + g + b) // 3
    if (r, g, b) == (255, 216, 0):  # sheet separator, never drawn
        return 0
    return 0 if l >= 192 else 1 if l >= 96 else 2 if l >= 32 else 3

dat = bytearray()
rows = []
for f in sorted(glob.glob(root + '/assets-fx/img/**/*.png', recursive=True)):
    rel = os.path.relpath(f, root + '/assets-fx')
    name = 'img_' + '_'.join(os.path.splitext(rel)[0].split('/')[1:])
    if name in SKIP:
        continue
    im = Image.open(f).convert('RGBA')
    px = [level(p) for p in im.tobytes() and zip(*[iter(im.tobytes())] * 4)]
    grey = bytearray((len(px) + 3) // 4)
    mask = bytearray((len(px) + 7) // 8)
    anym = False
    for i, v in enumerate(px):
        if v is None:
            mask[i >> 3] |= 1 << (i & 7)
            anym = True
        else:
            grey[i >> 2] |= v << ((i & 3) * 2)
    off = len(dat)
    dat += grey
    if anym:
        dat += mask
    rows.append((name, im.width, im.height, 1 if anym else 0, off, len(dat) - off))

with open(out + '/terrario.dat', 'wb') as o:
    o.write(dat)
with open(out + '/tr_images.c', 'w') as o:
    o.write('/* Generated by maketex.py from Terrario (KBD2), images CC BY 4.0. */\n#include "tr_gint.h"\n\n')
    for n, w, h, m, off, ln in rows:
        o.write('bopti_image_t %s = { %d, %d, %d, %d, %d, 0 };\n' % (n, w, h, m, off, ln))
    o.write('\nbopti_image_t *const tr_all_images[] = {\n')
    for n, *_ in rows:
        o.write('  &%s,\n' % n)
    o.write('};\nconst int tr_num_images = %d;\n' % len(rows))

f = Image.open(root + '/assets-fx/fonts/smalltext.png').convert('RGB')
with open(out + '/tr_font.c', 'w') as o:
    o.write('/* Generated by maketex.py from Terrario (KBD2), CC BY 4.0: ASCII 32..127, 5x6, bit 4 = leftmost. */\n')
    o.write('#include "tr_gint.h"\n\nconst unsigned char tr_font_glyphs[96][6] = {\n')
    for c in range(96):
        cx, cy = (c % 16) * 7, (c // 16) * 8
        rowsb = []
        for y in range(6):
            v = 0
            for x in range(5):
                if f.getpixel((cx + 1 + x, cy + 1 + y)) == (0, 0, 0):
                    v |= 1 << (4 - x)
            rowsb.append(v)
        o.write('  {%s},\n' % ','.join('0x%02x' % v for v in rowsb))
    o.write('};\n')
print(len(dat), 'bytes,', len(rows), 'images')
