#!/usr/bin/env python3
"""Generate <out>.c/.h (Flipper Icon structs) from images/*.png.
Usage: genicons.py images game_icons"""
import sys, glob, os
from PIL import Image

src, out = sys.argv[1], sys.argv[2]
icons = []
for f in sorted(glob.glob(os.path.join(src, "*.png"))):
    name = os.path.splitext(os.path.basename(f))[0]
    im = Image.open(f).convert("RGBA")
    w, h = im.size
    stride = (w + 7) // 8
    data = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a > 128 and (r + g + b) // 3 < 128:
                data[y * stride + x // 8] |= 1 << (x % 8)
    icons.append((name, w, h, data))

with open(out + ".h", "w") as f:
    f.write("/* Generated by genicons.py; do not edit. */\n#pragma once\n#include <gui/canvas.h>\n")
    f.write("#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
    for n, w, h, d in icons:
        f.write("extern const Icon I_%s;\n" % n)
    f.write("#ifdef __cplusplus\n}\n#endif\n")
with open(out + ".c", "w") as f:
    f.write("/* Generated by genicons.py; do not edit. */\n#include \"%s.h\"\n\n" % os.path.basename(out))
    for n, w, h, d in icons:
        f.write("static const uint8_t bits_%s[] = {%s};\n" % (n, ", ".join("0x%02x" % b for b in d)))
        f.write("static const uint8_t *const frames_%s[] = {bits_%s};\n" % (n, n))
        f.write("const Icon I_%s = {%d, %d, 1, 0, frames_%s};\n\n" % (n, w, h, n))
