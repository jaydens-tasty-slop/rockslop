#!/usr/bin/env python3
"""Generate flipper_fonts.c (ASCII 32..126) from Rockbox BDF fonts.
Usage: genfont.py ../../../fonts > flipper_fonts.c"""
import sys, os

FONTS = [("secondary", "08-Schumacher-Clean"),
         ("primary", "10-Adobe-Helvetica-Bold"),
         ("keyboard", "11-ProFont")]

def parse(path):
    asc = 0; glyphs = {}; cur = None; bits = False
    for line in open(path, encoding="latin-1"):
        t = line.split()
        if not t: continue
        if t[0] == "FONT_ASCENT": asc = int(t[1])
        elif t[0] == "STARTCHAR": cur = {"rows": []}
        elif t[0] == "ENCODING": cur["enc"] = int(t[1])
        elif t[0] == "DWIDTH": cur["dw"] = int(t[1])
        elif t[0] == "BBX": cur["bbx"] = tuple(int(v) for v in t[1:5])
        elif t[0] == "BITMAP": bits = True
        elif t[0] == "ENDCHAR":
            bits = False
            if 32 <= cur["enc"] <= 126: glyphs[cur["enc"]] = cur
        elif bits:
            w = cur["bbx"][0]
            v = int(t[0], 16) << (8 * (2 - len(t[0]) // 2)) if len(t[0]) <= 4 else 0
            cur["rows"].append(v & 0xFFFF)
    return asc, glyphs

def main():
    d = sys.argv[1]
    print("/* Generated by genfont.py from the Rockbox BDF fonts; do not edit. */")
    print('#include "flipper_fonts.h"\n')
    for name, bdf in FONTS:
        asc, g = parse(os.path.join(d, bdf + ".bdf"))
        rows = []; tab = []
        for c in range(32, 127):
            e = g.get(c) or g[63]
            w, h, xo, yo = e["bbx"]
            tab.append((e["dw"], w, h, xo, yo, len(rows)))
            rows += e["rows"]
        h = max(1, asc + max(0, -min(t[4] for t in tab)))
        print("static const uint16_t %s_rows[] = {" % name)
        for i in range(0, len(rows), 12):
            print("    " + ", ".join("0x%04x" % r for r in rows[i:i+12]) + ",")
        print("};")
        print("static const struct flip_glyph %s_glyphs[95] = {" % name)
        for t in tab: print("    {%d, %d, %d, %d, %d, %d}," % t)
        print("};")
        print("const struct flip_font flip_font_%s = {%d, %d, %s_glyphs, %s_rows};\n"
              % (name, asc, h, name, name))
main()
