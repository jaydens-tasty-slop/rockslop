#!/usr/bin/env python3
"""Generate rockbox/assets.c and assets.h from the RUMBLO sources.
Only the six map screens, the tiles they use, the two characters, the weapons
and the shield are kept. Run once; the output is checked in.
  python3 -I gen_assets.py <RUMBLO checkout> <rockbox dir>"""
import re, sys
src, outdir = sys.argv[1] + '/src/', sys.argv[2] + '/'

def bytes_of(path, name):
    s = open(src + path).read()
    m = re.search(name + r'\[\d+\]\s*=\s*\{(.*?)\};', s, re.S)
    return [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', m.group(1))]

pal = [tuple(map(int, m)) for m in re.findall(
    r'rgb\(\s*(\d+),\s*(\d+),\s*(\d+)\)', open(src + 'gfx/global_palette.c').read())]
tm = bytes_of('tilemap/tilemap.c', 'tilemap_map')
# screens: arena 0, arena 1 (three animation frames), win, lose
screens = [(3, 0), (4, 0), (5, 0), (6, 0), (7, 0), (0, 1)]
scr = [[tm[(sy * 15 + r) * 160 + sx * 20 + c] for r in range(15) for c in range(20)]
       for sx, sy in screens]
used = sorted({v for s in scr for v in s})
remap = {t: i for i, t in enumerate(used)}

def arr(decl, data, per):
    r = decl + ' = {\n'
    for i in range(0, len(data), per):
        r += '    ' + ','.join(str(v) for v in data[i:i + per]) + ',\n'
    return r + '};\n\n'

c = '/* Generated by gen_assets.py from RUMBLO (LGPL-3.0, see ../LICENSE). */\n#include "assets.h"\n\n'
c += arr('const unsigned char rumblo_palette[RUMBLO_COLORS * 3]', [v for p in pal for v in p], 24)
tiles = []
for t in used:
    tiles += bytes_of('gfx/tileset.c', 'tileset_tile_%d_data' % t)[2:]
c += arr('const unsigned char rumblo_tiles[RUMBLO_TILES][256]', tiles, 32)
c += arr('const unsigned char rumblo_screens[6][300]', [remap[v] for s in scr for v in s], 20)
frames = ['', 'Moving1', 'Moving2', 'NotGrounded']
chars = []
for ch in range(2):
    for f in frames:
        chars += bytes_of('gfx/character%d%s.c' % (ch, f), 'character%d%s_data' % (ch, f))[2:]
c += arr('const unsigned char rumblo_char[2][4][32 * 48]', chars, 32)
c += arr('const unsigned char rumblo_weapon[2][64]',
         [v for ch in range(2) for v in bytes_of('gfx/character%dWeapon.c' % ch, 'character%dWeapon_data' % ch)[2:]], 32)
c += arr('const unsigned char rumblo_shield[56 * 56]', bytes_of('gfx/shield.c', 'shield_data')[2:], 56)
open(outdir + 'assets.c', 'w').write(c)
open(outdir + 'assets.h', 'w').write('''/* RUMBLO artwork, indexed colour (index 0 transparent); see gen_assets.py. */
#ifndef RUMBLO_ASSETS_H
#define RUMBLO_ASSETS_H

#define RUMBLO_COLORS %d
#define RUMBLO_TILES %d

#define SCREEN_ARENA0 0 /* arena 1 has three animation frames: 1..3 */
#define SCREEN_ARENA1 1
#define SCREEN_WIN 4
#define SCREEN_LOSE 5

/* RGB triples */
extern const unsigned char rumblo_palette[RUMBLO_COLORS * 3];
/* 16x16 tiles, row major */
extern const unsigned char rumblo_tiles[RUMBLO_TILES][256];
/* 20x15 tile indices per screen */
extern const unsigned char rumblo_screens[6][300];
/* characters: stand, move 1, move 2, in the air; 32x48 facing right */
extern const unsigned char rumblo_char[2][4][32 * 48];
/* 8x8 projectile */
extern const unsigned char rumblo_weapon[2][64];
/* 56x56 */
extern const unsigned char rumblo_shield[56 * 56];

#endif
''' % (len(pal), len(used)))
