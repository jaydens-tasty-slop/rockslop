void menuItemPointerAnimation(){
  if(menuPointerPosDir){
    menuPointerPos++;
    if(menuPointerPos>=6){
      menuPointerPos=6;
      menuPointerPosDir=!menuPointerPosDir;
    }
  }else{
    menuPointerPos--;
    if(menuPointerPos<=-1){
      menuPointerPos=0;
      menuPointerPosDir=!menuPointerPosDir;
    }
  }
}

