static uint32_t hash_bytes(uint32_t h, const uint8_t *p, size_t n)
{
    while (n--) h=(h^*p++)*UINT32_C(16777619);
    return h;
}
static uint32_t read32(const uint8_t *p)
{
    return (uint32_t)p[0] | ((uint32_t)p[1]<<8) |
           ((uint32_t)p[2]<<16) | ((uint32_t)p[3]<<24);
}
static void write32(uint8_t *p, uint32_t v)
{
    for (int i=0;i<4;++i) p[i]=v>>(i*8);
}
#define SAVE_PATH_SIZE (sizeof(PLUGIN_GAMES_DATA_DIR) + sizeof("/rockcraft-a.bin"))
static void save_path(char *p, bool temp)
{
    rb->snprintf(p,SAVE_PATH_SIZE,PLUGIN_GAMES_DATA_DIR "/rockcraft-%c.%s",
                 'a'+slot,temp ? "tmp" : "bin");
}
static bool transfer(int fd, void *data, size_t n, bool writing)
{
    uint8_t *p=data;
    while (n) {
        ssize_t k=writing ? rb->write(fd,p,n) : rb->read(fd,p,n);
        if (k<=0) return false;
        n-=k; p+=k;
    }
    return true;
}

static bool save_world(void)
{
    char path[SAVE_PATH_SIZE], temp[SAVE_PATH_SIZE];
    uint8_t head[32]={'R','B','L','O','C','K','S','1',48,16,48};
    head[11]=player.x; head[12]=player.y; head[13]=player.z;
    head[14]=player.material; head[15]=player.height;
    write32(head+16,WORLD_BYTES);
    uint32_t hash=hash_bytes(UINT32_C(2166136261),head,20);
    write32(head+20,hash_bytes(hash,world_bits,WORLD_BYTES));
    save_path(path,false); save_path(temp,true);
    int fd=rb->open(temp,O_WRONLY|O_CREAT|O_TRUNC,0666);
    if (fd<0) return false;
    bool ok=transfer(fd,head,sizeof(head),true) &&
            transfer(fd,world_bits,WORLD_BYTES,true);
    if (rb->close(fd)<0) ok=false;
    if (ok && rb->rename(temp,path)<0) ok=false;
    if (!ok) rb->remove(temp);
    else dirty=false;
    return ok;
}

/* 0=missing, 1=valid, -1=unreadable/damaged. Called only at slot entry.
 * A damaged file is never silently replaced with a freshly generated map. */
static int load_world(void)
{
    char path[SAVE_PATH_SIZE]; uint8_t h[32], extra;
    save_path(path,false);
    if (!rb->file_exists(path)) return 0;
    int fd=rb->open(path,O_RDONLY);
    if (fd<0) return -1;
    bool ok=transfer(fd,h,sizeof(h),false);
    static const uint8_t magic[11]={'R','B','L','O','C','K','S','1',48,16,48};
    if (ok) {
        for (unsigned i=0;i<sizeof(magic);++i) if (h[i]!=magic[i]) ok=false;
        if (h[11]>=48 || h[12]>=16 || h[13]>=48 || h[14]<1 || h[14]>24 ||
            h[15]>1 || read32(h+16)!=WORLD_BYTES) ok=false;
    }
    if (ok) ok=transfer(fd,world_bits,WORLD_BYTES,false) && rb->read(fd,&extra,1)==0;
    if (rb->close(fd)<0) ok=false;
    if (ok) {
        uint32_t hash=hash_bytes(UINT32_C(2166136261),h,20);
        if (read32(h+20)!=hash_bytes(hash,world_bits,WORLD_BYTES)) ok=false;
        for (unsigned i=0;i<WORLD_SIZE*WORLD_SIZE*WORLD_HEIGHT && ok;++i)
            if (unpack5(world_bits,i)>GOLD) ok=false;
    }
    if (!ok) return -1;
    player.x=h[11]; player.y=h[12]; player.z=h[13];
    player.material=h[14]; player.height=h[15]; dirty=false;
    return 1;
}

static bool new_world(void)
{
    MENUITEM_STRINGLIST(kinds_menu,"New World",NULL,"Natural","Flat","Demo structures");
    int kind=rb->do_menu(&kinds_menu,NULL,NULL,false);
    if (kind<0 || kind>2 || usb) return false;
    rb->splash(0,"Generating...");
    rb->memset(world_bits,0,sizeof(world_bits));
    player.material=STONE; player.height=false;
    rng=(uint32_t)*rb->current_tick | 1;
    if (kind==0) generate_natural();
    else if (kind==1) generate_flat();
    else generate_demo();
    dirty=true;
    return true;
}

