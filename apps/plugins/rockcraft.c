{
    static const struct opt_items slots[]={
        {"World A",-1},{"World B",-1},{"World C",-1},{"World D",-1},{"World E",-1}};
    MENUITEM_STRINGLIST(menu,"Rockcraft",menu_cb,"Resume Game","Open World",
        "World Slot","New World","Materials","Height Mode","Save",
        "Playback Control","Save and Quit","Quit without Saving","Quit");
    int selected=0;
    bool quit=false, go=false;
    rb->lcd_setfont(FONT_UI);
    while (!go && !quit && !usb) {
        switch (rb->do_menu(&menu,&selected,NULL,false)) {
        case 0: go=true; break;
        case 1:
            if (ready && dirty && !rb->yesno_pop("Discard changes?")) break;
            slot=sel_slot;
            switch (load_world()) {
            case 1: ready=go=true; break;
            case 0: ready=go=new_world(); break;
            default: ready=false; rb->splash(HZ*2,"Save unreadable"); break;
            }
            break;
        case 2: rb->set_option("World Slot",&sel_slot,RB_INT,slots,5,NULL); break;
        case 3:
            if (dirty && !rb->yesno_pop("Discard changes?")) break;
            go=new_world();
            break;
        case 4: rb->lcd_setfont(FONT_SYSFIXED); picker(); rb->lcd_setfont(FONT_UI); break;
        case 5: rb->set_bool("Height Mode",&player.height); break;
        case 6:
        case 8:
            if (save_world()) {
                if (selected==8) quit=true;
                else rb->splash(HZ,"Saved");
            } else rb->splash(HZ*2,"Save failed");
            break;
        case 7: playback_control(NULL); break;
        case 9:
            if (!dirty || rb->yesno_pop("Discard changes?")) quit=true;
            break;
        case MENU_ATTACHED_USB: usb=true; break;
        case 10: quit=true; break;
        default: if (ready) go=true; else quit=true; break;
        }
    }
    rb->lcd_setfont(FONT_SYSFIXED);
    ui_colors();
    return quit || usb;
}

enum plugin_status plugin_start(const void *parameter)
{
    (void)parameter;
    usb=false; dirty=false;
    rb->memset(&input,0,sizeof(input)); rb->button_clear_queue();
    rb->memset(&gesture,0,sizeof(gesture));
    rb->lcd_set_viewport(NULL);
#if LCD_DEPTH > 1
    unsigned old_fg=rb->lcd_get_foreground(), old_bg=rb->lcd_get_background();
#endif
    int old_mode=rb->lcd_get_drawmode();
#if LCD_DEPTH >= 16
    fb_data *old_backdrop=rb->lcd_get_backdrop();
    rb->lcd_set_backdrop(NULL);
#endif
    #ifdef HAVE_TOUCHSCREEN
    int old_touch=rb->touchscreen_get_mode();
    rb->touchscreen_set_mode(TOUCHSCREEN_BUTTON);
#endif
    rb->lcd_setfont(FONT_SYSFIXED); backlight_ignore_timeout();
    ready=false; sel_slot=slot=0;
    if (game_menu()) ready=false;
    if (ready && !usb) render();
    while (ready && !usb) {
        int a=game_action();
        if (usb) break;
        bool redraw=true;
        int x=player.x,y=player.y,z=player.z;
        switch (a) {
        case INPUT_TAP: edit(); break;
        case INPUT_DOUBLE_UP: if (player.y<15) ++player.y; break;
        case INPUT_DOUBLE_DOWN: if (player.y>0) --player.y; break;
        case INPUT_BACK: case INPUT_DOUBLE_LEFT: picker(); break;
        case INPUT_MENU: case INPUT_DOUBLE_RIGHT: if (game_menu()) ready=false; else if (!usb) render(); break;
        case INPUT_UP:
            if (player.height) ++y; else ++x; break;
        case INPUT_DOWN:
            if (player.height) --y; else --x; break;
        case INPUT_LEFT: ++z; break;
        case INPUT_RIGHT: --z; break;
        default: redraw=false; break;
        }
        if (in_world(x,y,z) && (x!=player.x || y!=player.y || z!=player.z)) {
            /* Only movement actions may replace coordinates; menus can create
             * a new world with a different cursor position. */
            if (a>=INPUT_UP && a<=INPUT_RIGHT)
                { player.x=x; player.y=y; player.z=z; }
        }
        if (redraw && ready && !usb) render();
    }
    #ifdef HAVE_TOUCHSCREEN
    rb->touchscreen_set_mode(old_touch);
#endif
    backlight_use_settings(); rb->lcd_setfont(FONT_UI);
    rb->lcd_set_drawmode(old_mode);
#if LCD_DEPTH > 1
    rb->lcd_set_foreground(old_fg); rb->lcd_set_background(old_bg);
#endif
#if LCD_DEPTH >= 16
    rb->lcd_set_backdrop(old_backdrop);
#endif
    return usb ? PLUGIN_USB_CONNECTED : PLUGIN_OK;
}
