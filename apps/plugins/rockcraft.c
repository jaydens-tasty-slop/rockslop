/* Menus retain ordinary D-pad navigation. Gestures apply only to the world. */
static int action(void)
{
    int a=read_input();
    return (a & INPUT_RELEASE) ? INPUT_NONE : a & ~INPUT_REPEAT;
}

#ifndef ROCKCRAFT_DOUBLE_TICKS
#define ROCKCRAFT_DOUBLE_TICKS (HZ*3/10)
#endif

/* A first tap moves immediately. A second matching tap within 300 ms restores
 * the first tap's cursor position before running its shortcut. Holding a
 * direction repeats movement and cancels double-tap eligibility. No world
 * edits are undone: any intervening edit/different direction cancels it. */
static int game_action(void)
{
#ifdef PORT_CENTER_BUTTON
    /* Common pause gesture: hold Select+Up for 0.5 s. Select alone acts only
     * on a click, so the chord is free; its release must not click. */
    static unsigned long chord_since; static bool chord_done;
    if ((rb->button_status()&(PORT_CENTER_BUTTON|BUTTON_UP))==(PORT_CENTER_BUTTON|BUTTON_UP)) {
        if (!chord_since) chord_since=*rb->current_tick|1;
        else if (!chord_done && *rb->current_tick-chord_since>=(unsigned long)(HZ/2)) {
            chord_done=true; input.held=0; input.used=true; input.suppress=INPUT_UP;
            gesture.phase=0; return INPUT_MENU;
        }
    } else { chord_since=0; chord_done=false; }
#endif
    int a=read_input(), dir=a & ~(INPUT_REPEAT|INPUT_RELEASE);
    unsigned long elapsed=(unsigned long)*rb->current_tick-(unsigned long)gesture.when;
    if (dir>=INPUT_UP && dir<=INPUT_RIGHT) {
        if (a & INPUT_RELEASE) {
            if (gesture.phase==1 && gesture.direction==dir && elapsed<ROCKCRAFT_DOUBLE_TICKS) {
                gesture.phase=2; gesture.when=*rb->current_tick;
            } else gesture.phase=0;
            return INPUT_NONE;
        }
        if (a & INPUT_REPEAT) {
            if (gesture.phase==3 && gesture.direction==dir)
                return INPUT_DOUBLE_UP+dir-INPUT_UP;
            gesture.phase=0; return dir;
        }
        if (gesture.phase==2 && gesture.direction==dir && elapsed<=ROCKCRAFT_DOUBLE_TICKS) {
            #ifdef ROCKCRAFT_RAW_INPUT
            static const unsigned masks[]={ROCKCRAFT_UP,ROCKCRAFT_DOWN,ROCKCRAFT_LEFT,ROCKCRAFT_RIGHT};
#endif
            player.x=gesture.x; player.y=gesture.y; player.z=gesture.z;
            /* Vertical shortcuts latch until release: hold the second tap
             * to climb rapidly. Menu/picker shortcuts swallow their held
             * key so its repeats cannot select an unintended menu entry. */
            if (dir<=INPUT_DOWN) gesture.phase=3;
            else {
                gesture.phase=0;
#ifdef ROCKCRAFT_RAW_INPUT
                input.suppress=masks[dir-INPUT_UP];
#else
                input.suppress=dir;
#endif
            }
            return INPUT_DOUBLE_UP+dir-INPUT_UP;
        }
        gesture.direction=dir;
#ifdef ROCKCRAFT_RAW_INPUT
        gesture.phase=1;
#else
        gesture.phase=2; /* PLA directions have press/repeat but no release. */
#endif
        gesture.when=*rb->current_tick;
        gesture.x=player.x; gesture.y=player.y; gesture.z=player.z;
        return dir;
    }
    if (a==INPUT_TAP || a==INPUT_BACK || a==INPUT_MENU) gesture.phase=0;
    return a;
}

