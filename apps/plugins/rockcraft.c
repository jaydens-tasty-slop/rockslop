static bool in_world(int x, int y, int z)
{
    return (unsigned)x < WORLD_SIZE && (unsigned)y < WORLD_HEIGHT &&
           (unsigned)z < WORLD_SIZE;
}

/* Last voxel ends exactly at the last byte: never read a padding byte. */
static unsigned unpack5(const uint8_t *p, unsigned i)
{
    unsigned bit = i * 5, n = bit >> 3, s = bit & 7;
    unsigned v = p[n] >> s;
    if (s > 3) v |= (unsigned)p[n + 1] << (8 - s);
    return v & 31;
}

static unsigned get_block(int x, int y, int z)
{
    if (!in_world(x, y, z)) return AIR;
    return unpack5(world_bits, (y * WORLD_SIZE + x) * WORLD_SIZE + z);
}

static void put_block(int x, int y, int z, unsigned v)
{
    if (!in_world(x, y, z) || v > GOLD) return;
    unsigned bit = ((y * WORLD_SIZE + x) * WORLD_SIZE + z) * 5;
    unsigned n = bit >> 3, s = bit & 7;
    world_bits[n] = (world_bits[n] & ~(31u << s)) | (v << s);
    if (s > 3)
        world_bits[n+1] = (world_bits[n+1] & ~(31u >> (8-s))) | (v >> (8-s));
}

static uint32_t random32(void)
{
    rng ^= rng << 13; rng ^= rng >> 17; rng ^= rng << 5;
    return rng;
}

static void fill_space(int x0, int y0, int z0, int x1, int y1, int z1, int b)
{
    for (int y=y0; y<=y1; ++y)
        for (int x=x0; x<=x1; ++x)
            for (int z=z0; z<=z1; ++z) put_block(x,y,z,b);
}

static void add_tree(int x, int y, int z)
{
    fill_space(x-2,y+3,z-2,x+2,y+4,z+2,LEAVES);
    fill_space(x-1,y+5,z-1,x+1,y+5,z+1,LEAVES);
    fill_space(x-1,y+6,z,x+1,y+6,z,LEAVES);
    fill_space(x,y+6,z-1,x,y+6,z+1,LEAVES);
    fill_space(x,y,z,x,y+5,z,WOOD);
}

#define WATER_LEVEL 5

#define GRID_STEP 8
#define GRID_OFFSET (GRID_STEP / 2)
#define GRID_SIZE ((WORLD_SIZE / GRID_STEP) + 1)

// Makes a "natural" looking world with randomly generated terrain and trees
static void generate_natural(void) {
    // Add bedrock floor
    fill_space(0, 0, 0, WORLD_SIZE - 1,           0, WORLD_SIZE - 1, BEDROCK);
    fill_space(0, 1, 0, WORLD_SIZE - 1, WATER_LEVEL, WORLD_SIZE - 1, WATER);

    uint8_t grid[GRID_SIZE][GRID_SIZE];

    for(uint8_t x = 0; x < GRID_SIZE; x++) {
        for(uint8_t z = 0; z < GRID_SIZE; z++) {
            grid[x][z] = (3 + random32() % 10);
        }
    }


    for(uint8_t x = 0; x < WORLD_SIZE; x++) {
        for(uint8_t z = 0; z < WORLD_SIZE; z++) {
            uint8_t grid_x = x / GRID_STEP;
            uint8_t grid_z = z / GRID_STEP;

            uint8_t lerp_x = x - (grid_x * GRID_STEP);
            uint8_t lerp_z = z - (grid_z * GRID_STEP);

            uint16_t height = 0;

            height += grid[grid_x    ][grid_z    ] * (GRID_STEP - lerp_x) * (GRID_STEP - lerp_z);
            height += grid[grid_x + 1][grid_z    ] * (            lerp_x) * (GRID_STEP - lerp_z);
            height += grid[grid_x    ][grid_z + 1] * (GRID_STEP - lerp_x) * (            lerp_z);
            height += grid[grid_x + 1][grid_z + 1] * (            lerp_x) * (            lerp_z);

            height /= GRID_STEP * GRID_STEP;

            if(height > 3) {
                fill_space(x, 1, z, x, height - 3, z, STONE);
                fill_space(x, height - 2, z, x, height, z, DIRT);
            }
            else 
            {   
                fill_space(x, 1, z, x, height, z, DIRT);
            }
            
            if(height >= WATER_LEVEL)
                fill_space(x, height, z, x, height, z, GRASS);
        }   
    }

    // Replace dirt with sand near water blocks
    for(uint8_t y = WATER_LEVEL - 1; y <= WATER_LEVEL; y++) {
        for(uint8_t x = 0; x < WORLD_SIZE; x++) {
            for(uint8_t z = 0; z < WORLD_SIZE; z++) {
                if(get_block(x, y, z) != GRASS && get_block(x, y, z) != DIRT) continue;
                if(y >= WORLD_HEIGHT - 1) continue;
                if(get_block(x, y + 1, z) != AIR && get_block(x, y + 1, z) != WATER) continue;

                bool near_water = false;

                for(int8_t by = -1; by <= 1; by++) {
                    if(y + by < 0 || y + by >= WORLD_HEIGHT) continue;

                    for(int8_t bx = -2; bx <= 2; bx++) {
                        if(x + bx < 0 || x + bx >= WORLD_SIZE) continue;
                        
                        for(int8_t bz = -2; bz <= 2; bz++) {
                            if(z + bz < 0 || z + bz >= WORLD_SIZE) continue;

                            if(get_block(bx + x, by + y, bz + z) == WATER)
                                near_water = true;
                        }
                    }
                }

                if(near_water)
                    put_block(x, y, z, SAND);
            }
        }
    }

    //Add trees
    uint8_t tree_cnt = 12;
    for(uint8_t i = 0; i < tree_cnt; i++) {
        //uint8_t x = 2;//randInt(2, WORLD_SIZE - 2 - 1);
        //uint8_t z = 2;//randInt(2, WORLD_SIZE - 2 - 1);
        // Weird little hack I need to do since clang crashes with the above lines :(
        uint8_t x = 2 + (random32() % (WORLD_SIZE - 1 - 4));
        uint8_t z = 2 + (random32() % (WORLD_SIZE - 1 - 4));

        int8_t y = WORLD_HEIGHT - 8;

        if(get_block(x, y + 1, z) != AIR) continue;

        while(y > 0) {
            if(get_block(x, y, z) != AIR) break; 
            y--;
        }

        if(get_block(x, y, z) != GRASS) continue;

        add_tree(x, y + 1, z);
        put_block(x, y, z, DIRT);
    }

    // Replace a few stone blocks with coal
    for(uint8_t y = 1; y < WORLD_HEIGHT; y++) {
        for(uint8_t x = 0; x < WORLD_SIZE; x++) {
            for(uint8_t z = 0; z < WORLD_SIZE; z++) {
                if(get_block(x, y, z) != STONE) continue;

                int r = (random32() % 20);

                // Replace stone with coal or iron ore at a 10% chance
                if(r == 0) {
                    put_block(x, y, z, COAL_ORE);
                }
                else if(r == 1) {
                    put_block(x, y, z, IRON_ORE);
                }
            }
        }
    }

    // Center the player in the world and place them at the lowest open-air block
    player.x = WORLD_SIZE / 2;
    player.y = 0;
    player.z = WORLD_SIZE / 2;

    while(player.y < (WORLD_HEIGHT - 1)) {
        if(get_block(player.x, player.y, player.z) == AIR) break;
        player.y++;
    }
}

