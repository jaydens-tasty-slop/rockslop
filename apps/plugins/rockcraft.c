static int read_input(void)
{
    int a=pluginlib_getaction(HZ/30 > 0 ? HZ/30 : 1,contexts,ARRAYLEN(contexts));
    if (rb->default_event_handler(a)==SYS_USB_CONNECTED) { usb=true; return INPUT_NONE; }
    if (a==PLA_SELECT) { input.held=1; input.used=false; input.since=*rb->current_tick; input.suppress=0; return INPUT_NONE; }
    if (a==PLA_SELECT_REPEAT) { input.held=0; input.used=true; return INPUT_NONE; }
    if (a==PLA_SELECT_REL) {
        bool click=input.held && !input.used &&
            (unsigned long)*rb->current_tick-(unsigned long)input.since < (unsigned)(HZ*3/5);
        input.held=0; return click ? INPUT_TAP : INPUT_NONE;
    }
    if (a==PLA_CANCEL) return INPUT_BACK;
    if (a==PLA_EXIT) return INPUT_MENU;
    int d=INPUT_NONE; bool repeat=false;
    switch (a) {
    case PLA_UP: d=INPUT_UP; break;
    case PLA_DOWN: d=INPUT_DOWN; break;
    case PLA_LEFT: d=INPUT_LEFT; break;
    case PLA_RIGHT: d=INPUT_RIGHT; break;
    case PLA_UP_REPEAT: d=INPUT_UP; repeat=true; break;
    case PLA_DOWN_REPEAT: d=INPUT_DOWN; repeat=true; break;
    case PLA_LEFT_REPEAT: d=INPUT_LEFT; repeat=true; break;
    case PLA_RIGHT_REPEAT: d=INPUT_RIGHT; repeat=true; break;
#ifdef HAVE_SCROLLWHEEL
    /* Wheel detents never count as double taps. Use Menu/Play for vertical
     * double taps on iPods; the wheel is convenient for lists and movement. */
    case PLA_SCROLL_BACK: case PLA_SCROLL_BACK_REPEAT: d=INPUT_UP; repeat=true; break;
    case PLA_SCROLL_FWD: case PLA_SCROLL_FWD_REPEAT: d=INPUT_DOWN; repeat=true; break;
#endif
    }
    if (!d) return INPUT_NONE;
    /* Standard keymaps often omit release after Select repeat. A following
     * direction must still work, even if the reserved hold ate its release. */
    if (input.held) { input.held=0; input.used=true; }
    if (repeat && input.suppress==(unsigned)d) return INPUT_NONE;
    if (!repeat) input.suppress=0;
    return d | (repeat ? INPUT_REPEAT : 0);
}
