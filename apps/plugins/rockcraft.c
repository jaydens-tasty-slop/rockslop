static int row_width(int r)
{
    return r < 48 ? 2*(r+1) : r < 80 ? 96 : 2*(127-r);
}

static int row_offset(int r) { return row_width(r)/2-r-1; }

struct hit { int x,y,z,depth; unsigned block, face; };

/* Upstream's isometric inverse, with bounded, signed arithmetic. Trace only
 * the intersection with the 48x48x16 volume. No ray recursion or hit lists.
 * Bounded numerators are nonnegative, so C division is exact floor division.
 * Each candidate is checked against forward projection to reject the gaps
 * between a voxel's three depth phases. */
static bool trace(int row, int idx, int start, int stop, bool light,
                  unsigned skip, struct hit *h)
{
    int b = idx-row_offset(row), p = (b & 1) ? 4 : 2;
    for (int d=start; d<=stop; ++d) {
        int c = d-15;
        int nx = -2*row+3*b+2*c, ny = 2*row-2*c;
        int nz = 4*row-3*b+2*c+p;
        if (nx < 0 || ny < 0 || nz < 0 || nx >= 288 || ny >= 96 || nz >= 288)
            continue;
        int x=nx/6, y=ny/6, z=nz/6;
        if (x+z+15-y != d) continue;
        int s=row-x-2*y-z;
        int t=idx-(2*x+2*y+row_offset(row)+s);
        if ((unsigned)s > 2 || (unsigned)t > 1) continue;
        unsigned block = light ? get_block(z,y,47-x) : get_block(x,y,z);
        if (block <= skip) continue;
        h->x=x; h->y=y; h->z=z; h->depth=d; h->block=block;
        h->face = s == 2 ? 2 : t;
        return true;
    }
    return false;
}

static unsigned shadow_at(const struct hit *h)
{
#if ROCKCRAFT_SHADOWS
    if (h->face == 1) return 0; /* Right face is shaded in the artwork. */
    int x=47-h->z, y=h->y, z=h->x, d=x+z+15-y;
    struct hit sh;
    unsigned flags=0;
    if (h->face == 2) {
        int r=x+2*y+z+2, i=2*x+2*y+row_offset(r)+2;
        if (trace(r,i,0,d-1,true,WATER,&sh)) flags |= 2;
        if (trace(r,i+1,0,d-1,true,WATER,&sh)) flags |= 1;
    } else {
        int r=x+2*y+z+1, i=2*x+2*y+row_offset(r)+2;
        if (trace(r,i,0,d-1,true,WATER,&sh)) flags |= 2;
        --r; i=2*x+2*y+row_offset(r)+1;
        if (trace(r,i,0,d-1,true,WATER,&sh)) flags |= 1;
    }
    return flags;
#else
    (void)h; return 0;
#endif
}

static unsigned water_at(const struct hit *h, int row, bool right)
{
    if (get_block(h->x,h->y+1,h->z) == WATER) return 2;
    bool left_half=get_block(h->x,h->y,h->z+1)!=WATER;
    bool right_half=get_block(h->x+1,h->y,h->z)!=WATER;
    int s=row-h->x-2*h->y-h->z;
    if (s == 0) return 2;
    bool half=right ? right_half : left_half;
    if (s == 2) half |= get_block(h->x+1,h->y,h->z+1)!=WATER;
    return half ? 1 : 2;
}

static unsigned texel(unsigned block, unsigned tri, unsigned pixel)
{
    const uint8_t *p = block_tex[(block-2)*6+tri];
    unsigned bit=pixel*6, n=bit>>3, s=bit&7;
    unsigned v=p[n]>>s;
    if (s > 2) v |= (unsigned)p[n+1] << (8-s);
    return v & 63;
}

static void rgb(unsigned index, unsigned *r, unsigned *g, unsigned *b)
{
    unsigned v=palette555[index];
    *r=((v>>10)&31)*255/31; *g=((v>>5)&31)*255/31; *b=(v&31)*255/31;
}

/* Draw directly into Rockbox's existing framebuffer. At most 8 pixels of
 * native output are on the stack, irrespective of screen dimensions. */
static void span(int x, int y, const uint8_t *pixels, int n)
{
    if (y<0 || y>=VIEW_HEIGHT || x>=RB_WIDTH || x+n<=0) return;
    if (x<0) { pixels-=x; n+=x; x=0; }
    if (x+n>RB_WIDTH) n=RB_WIDTH-x;
x=x*ROCKCRAFT_SCALE+(LCD_WIDTH-RB_WIDTH*ROCKCRAFT_SCALE)/2;
    y*=ROCKCRAFT_SCALE; n*=ROCKCRAFT_SCALE;
#ifdef HAVE_LCD_COLOR
    fb_data out[8 * ROCKCRAFT_SCALE];
#elif LCD_DEPTH == 1
    uint8_t out[8 * ROCKCRAFT_SCALE];
#endif
    for (int i=0; i<n; ++i) {
        unsigned r,g,b; rgb(pixels[i/ROCKCRAFT_SCALE],&r,&g,&b);
#if ROCKCRAFT_COLOR
        out[i]=FB_RGBPACK(r,g,b);
#else
        unsigned gray=(77*r+150*g+29*b)>>8;
#if LCD_DEPTH == 2
        rb->lcd_set_foreground(LCD_BRIGHTNESS(gray));
        for (int j=0;j<ROCKCRAFT_SCALE;++j) rb->lcd_drawpixel(x+i,y+j);
#else
        static const uint8_t dither[4][4]={{0,8,2,10},{12,4,14,6},{3,11,1,9},{15,7,13,5}};
        bool white=gray > (unsigned)(dither[y&3][(x+i)&3]*16+8);
#ifdef HAVE_LCD_COLOR
        out[i]=white ? FB_RGBPACK(255,255,255) : FB_RGBPACK(0,0,0);
#else
        out[i]=white ? 0 : 1; /* Mono bit 1 draws foreground (black). */
#endif
#endif
#endif
    }
#ifdef HAVE_LCD_COLOR
    for (int j=0;j<ROCKCRAFT_SCALE;++j) rb->lcd_bitmap(out,x,y+j,n,1);
#elif LCD_DEPTH == 1
    for (int j=0;j<ROCKCRAFT_SCALE;++j) rb->lcd_mono_bitmap(out,x,y+j,n,1);
#endif
}

static void triangle(int x, int y, bool right, unsigned block, unsigned face,
                     unsigned shadow, unsigned water)
{
    unsigned tri=face*2+right, k=0;
    uint32_t sm=shadow_bits[shadow][tri], wm=water_bits[water][tri];
    for (int r=0; r<7; ++r) {
        int w=r<4 ? 2*(r+1) : 2*(7-r);
        uint8_t line[8];
        for (int i=0; i<w; ++i,++k)
            line[i]=(block>=STONE ? texel(block,tri,k) : 0) |
                    (((sm>>k)&1)*64) | (((wm>>k)&1)*128);
        span(right ? x : x-w,y+r,line,w);
    }
}

