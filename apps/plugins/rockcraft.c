static void render(void)
{
    int cx=RB_WIDTH/2-8*player.x+8*player.z;
    int cy=VIEW_HEIGHT/2-8+4*player.x+4*player.z+8*player.y;
    ui_colors();
#if ROCKCRAFT_COLOR
    unsigned r,g,b; rgb(0,&r,&g,&b);
    rb->lcd_set_background(LCD_RGBPACK(r,g,b));
#endif
    rb->lcd_clear_display();
    for (int row=0; row<ROW_COUNT; ++row) {
        int sy=cy+8-row*4;
        if (sy+7<=0 || sy>=VIEW_HEIGHT) continue;
        int width=row_width(row), off=row_offset(row);
        for (int i=0; i<width; ++i) {
            bool right=((i-off)&1)!=0;
            int sx=cx-width*4+8+i*8-(right ? 8 : 0);
            if (sx+(right ? 8 : 0)<=0 || sx-(right ? 0 : 8)>=RB_WIDTH) continue;
            struct hit h, solid;
            unsigned water=0, shadow=0, block=AIR, face=0;
            if (trace(row,i,0,MAX_DEPTH,false,AIR,&h)) {
                if (h.block == WATER) {
                    water=water_at(&h,row,right);
                    if (trace(row,i,h.depth+1,MAX_DEPTH,false,WATER,&solid)) h=solid;
                }
                if (h.block >= STONE) {
                    block=h.block; face=h.face; shadow=shadow_at(&h);
                }
            }
            triangle(sx,sy,right,block,face,shadow,water);
        }
        rb->yield();
    }
    /* Always-visible cursor: dark outline and white wireframe. It identifies
     * the exact editable voxel even when that voxel is hidden by a wall. */
    int x=RB_WIDTH/2, y=VIEW_HEIGHT/2-8;
    static const int8_t edges[9][4]={
        {0,0,-8,4},{0,0,8,4},{-8,4,0,8},{8,4,0,8},
        {-8,4,-8,12},{8,4,8,12},{0,8,0,16},
        {-8,12,0,16},{8,12,0,16}
    };
    ui_colors();
    for (int k=-1; k<=0; ++k) {
#if LCD_DEPTH > 1
        rb->lcd_set_foreground(k ? LCD_BLACK : LCD_WHITE);
#else
        rb->lcd_set_drawmode(k ? DRMODE_SOLID : DRMODE_SOLID|DRMODE_INVERSEVID);
#endif
        for (int i=0; i<9; ++i)
            rb->lcd_drawline((x+edges[i][0])*ROCKCRAFT_SCALE,(y+edges[i][1])*ROCKCRAFT_SCALE+k,
                             (x+edges[i][2])*ROCKCRAFT_SCALE,(y+edges[i][3])*ROCKCRAFT_SCALE+k);
    }
    hud(); rb->lcd_update();
}

