#!/usr/bin/env python3
"""Move a Pokitto game's image arrays out of the plugin image.

usage: pk_images.py IMAGES_DIR [--blob FILE] [--header FILE] [--cpp FILE]

IMAGES_DIR is the upstream src/images tree; its Images.h includes (recursively)
header files that define
`const uint8_t Name[] = {...};` and `const uint8_t * const Name[] = {A, B};`
inside `namespace Images`. The arrays are packed (4-byte aligned, in include
order) into --blob, which the game loads into the audio buffer at
start. --header writes the replacement Images.h (pointer variables instead
of arrays) and --cpp the matching definitions plus pk_images_init(base),
which points every variable at its place in the blob. The header and cpp
are checked into the port; the blob is extracted at build time from the
upstream sources, so all three outputs always agree.
"""
import os, re, sys

ARRAY = re.compile(
    r'(?:inline\s+)?(?:constexpr\s+|const\s+)+uint8_t\s+(?:PROGMEM\s+)?(\w+)\s*'
    r'\[\s*\]\s*(?:PROGMEM\s*)?=\s*\{([^}]*)\}\s*;')
PTRARRAY = re.compile(
    r'(?:inline\s+)?(?:constexpr\s+)?const\s+uint8_t\s*\*\s*const\s+(?:PROGMEM\s+)?(\w+)\s*'
    r'\[\s*\d*\s*\]\s*(?:PROGMEM\s*)?=\s*\{([^}]*)\}\s*;')


def resolve(path):
    """The path with each component's case fixed up to match the disk (the
    upstream sources were written on a case-insensitive file system)."""
    cur = ''
    for part in os.path.normpath(path).split(os.sep):
        base = cur or (os.sep if path.startswith(os.sep) else '.')
        if part and not os.path.exists(os.path.join(base, part)) and os.path.isdir(base):
            for n in os.listdir(base):
                if n.lower() == part.lower():
                    part = n
                    break
        cur = os.path.join(cur, part) if cur else (os.sep + part if path.startswith(os.sep) else part)
    return cur


def walk(path, done):
    """Header files in include order, starting from path (each once)."""
    path = resolve(path)
    if path in done or not os.path.exists(path):
        return
    done.add(path)
    text = open(path, encoding='utf-8', errors='replace').read()
    yield path, text
    for inc in re.findall(r'#\s*include\s*"([^"]+)"', text):
        yield from walk(os.path.join(os.path.dirname(path), inc), done)


def parse(root):
    arrays, ptrs = [], []
    seen = set()
    for path, text in walk(os.path.join(root, 'Images.h'), set()):
        text = re.sub(r'//[^\n]*|/\*.*?\*/', '', text, flags=re.S)
        for m in ARRAY.finditer(text):
            name = m.group(1)
            data = bytes(int(v, 16) if v.lower().startswith('0x') else int(v)
                         for v in re.findall(r'0[xX][0-9a-fA-F]+|\d+', m.group(2)))
            if name in seen:
                sys.exit('duplicate image ' + name)
            seen.add(name)
            arrays.append((name, data))
        for m in PTRARRAY.finditer(text):
            name = m.group(1)
            elems = [e.strip() for e in m.group(2).split(',') if e.strip()]
            elems = ['nullptr' if e in ('0', 'NULL') else e for e in elems]
            if name in seen:
                sys.exit('duplicate image ' + name)
            seen.add(name)
            ptrs.append((name, elems))
    for name, elems in ptrs:
        for e in elems:
            if e not in seen and e != 'nullptr':
                sys.exit(f'{name}: unknown element {e}')
    return arrays, ptrs


def main():
    args = sys.argv[1:]
    root = args.pop(0)
    out = dict(zip(args[::2], args[1::2]))
    arrays, ptrs = parse(root)
    blob = bytearray()
    offsets = {}
    for name, data in arrays:
        offsets[name] = len(blob)
        blob += data
        blob += b'\0' * (-len(blob) % 4)
    if '--blob' in out:
        open(out['--blob'], 'wb').write(blob)
    if '--header' in out:
        with open(out['--header'], 'w') as f:
            f.write('// Generated by tools/pk_images.py: the image data is in images.bin on the card.\n'
                    '#pragma once\n\n#include <stdint.h>\n\n'
                    'void pk_images_init(const uint8_t *blob);\n\nnamespace Images {\n\n')
            for name, _ in arrays:
                f.write(f'    extern const uint8_t *{name};\n')
            for name, elems in ptrs:
                f.write(f'    extern const uint8_t *{name}[{len(elems)}];\n')
            f.write('\n}\n')
    if '--cpp' in out:
        with open(out['--cpp'], 'w') as f:
            f.write('// Generated by tools/pk_images.py.\n#include "Images.h"\n\nnamespace Images {\n\n')
            for name, _ in arrays:
                f.write(f'    const uint8_t *{name};\n')
            for name, elems in ptrs:
                f.write(f'    const uint8_t *{name}[{len(elems)}];\n')
            f.write('\n}\n\nvoid pk_images_init(const uint8_t *blob)\n{\n')
            for name, _ in arrays:
                f.write(f'    Images::{name} = blob + {offsets[name]};\n')
            for name, elems in ptrs:
                for i, e in enumerate(elems):
                    f.write(f'    Images::{name}[{i}] = ' + ('nullptr' if e == 'nullptr' else f'Images::{e}') + ';\n')
            f.write('}\n')
    print(f'{len(arrays)} images, {len(ptrs)} tables, {len(blob)} bytes', file=sys.stderr)


main()
