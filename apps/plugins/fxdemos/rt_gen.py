#!/usr/bin/env python3
"""Generate rt_tables.h and rt_wood.h from the TI-84 CE Raytracing sources.
usage: rt_gen.py <path to TI-84-CE-Raytracing/src>"""
import re, sys

src = sys.argv[1]

def array(text, name):
    m = re.search(name + r'\[[^\]]*\]\s*\{(.*?)\}\s*;?', text, re.S)
    return [int(x) for x in re.findall(r'-?\d+', m.group(1))]

def emit(f, ctype, name, vals, per=12):
    f.write('static const %s %s[%d] = {\n' % (ctype, name, len(vals)))
    for i in range(0, len(vals), per):
        f.write('  ' + ', '.join(str(v) for v in vals[i:i + per]) + ',\n')
    f.write('};\n')

spec = open(src + '/spectrum.h').read()
fixed = open(src + '/fixedpoint.h').read()
with open('rt_tables.h', 'w') as f:
    f.write('/* Generated by rt_gen.py from spectrum.h and fixedpoint.h of\n'
            ' * TI-84-CE-Raytracing (MIT). Q12 sRGB->linear tables and arcsin(x)/(pi/2). */\n')
    # upstream lists 255 values; the 256th is zero there, which makes the
    # binary search wrap to black for the brightest values. Use a sentinel.
    emit(f, 'uint16_t', 'gamma_lut', array(spec, 'gamma_LUT') + [65535])
    emit(f, 'int16_t', 'degamma_lut', array(spec, 'degamma_LUT'))
    emit(f, 'int16_t', 'asin_table', array(fixed, 'asin_table'))

tex = open(src + '/texture.h').read()
rows = re.findall(r'\{((?:0x[0-9a-fA-F]+,?\s*)+)\}', tex[tex.index('wood_tex'):])
rows = rows[:128]
assert all(len(re.findall('0x', r)) == 128 for r in rows)
with open('rt_wood.h', 'w') as f:
    f.write('/* Generated by rt_gen.py: the 128x128 wood floor texture of\n'
            ' * TI-84-CE-Raytracing (MIT), colours as (r << 11) | (g << 6) | b, 5 bits each. */\n')
    f.write('static const uint16_t rt_wood[128][128] = {\n')
    for r in rows:
        f.write('  {' + ','.join(re.findall(r'0x[0-9a-fA-F]+', r)) + '},\n')
    f.write('};\n')
