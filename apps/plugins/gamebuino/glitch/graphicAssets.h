/* The eight 240x128 background images live in decor.dat on the card
 * (rocks/games/gamebuino/glitch/); only the current one is in RAM. */
static const uint16_t DECOR_RECORD_SIZE = 15367;
static uint8_t decorBuffer[DECOR_RECORD_SIZE];
static int8_t decorLoaded = -1;
static Image decorImage;

static Image &decorMap(uint8_t index)
{
    if (decorLoaded != index) {
        if (gb_data_read("decor.dat", (uint32_t)index * DECOR_RECORD_SIZE,
                         decorBuffer, sizeof(decorBuffer))
                != (int)sizeof(decorBuffer))
            memset(decorBuffer, 0, sizeof(decorBuffer));
        decorImage = Image((const uint8_t *)decorBuffer);
        decorLoaded = index;
    }
    return decorImage;
}

