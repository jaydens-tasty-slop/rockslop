#!/usr/bin/env python3
"""Regenerates textures.h: shrinks small3dlib's RGBA example textures (C
headers) to 64x64 RGB565 so they fit the plugin arena. Usage:
  maketex.py PROGRAMS_DIR > textures.h
Colours are stored as plain (unswapped) RGB565; s3l_rb.h converts."""
import re, sys

def load(path, want):
    t = open(path).read()
    m = re.search(r'const\s+uint8_t\s+' + want + r'\[\d+\]\s*=\s*\{([^}]*)\}', t)
    return [int(x) for x in re.findall(r'\d+', m.group(1))]

def shrink(data, w, nearest):
    out = []
    f = w // 64
    for y in range(64):
        for x in range(64):
            if nearest or f == 1:
                px = [data[((y * f) * w + x * f) * 4 + c] for c in range(3)]
            else:
                px = [0, 0, 0]
                for j in range(f):
                    for i in range(f):
                        for c in range(3):
                            px[c] += data[((y * f + j) * w + x * f + i) * 4 + c]
                px = [v // (f * f) for v in px]
            out.append(((px[0] >> 3) << 11) | ((px[1] >> 2) << 5) | (px[2] >> 3))
    return out

d = sys.argv[1]
print("/* Generated by maketex.py from small3dlib's example textures (CC0). */")
print("#ifndef TEXTURES_H\n#define TEXTURES_H\n#include <stdint.h>\n")
for name, src, w, nearest in (
        ("level1Texture", "levelTextures", 64, 0),
        ("level2Texture", "levelTextures", 64, 0),
        ("level3Texture", "levelTextures", 64, 0),
        ("cityTexture", "cityTexture", 256, 0),
        ("houseTexture", "houseTexture", 128, 0),
        ("chestTexture", "chestTexture", 128, 0),
        ("plantTexture", "plantTexture", 128, 1),
        ("catTexture", "catTexture", 128, 0)):
    data = load("%s/%s.h" % (d, src), name)
    px = shrink(data, w, nearest)
    print("static const uint16_t %s[64 * 64] = {" % name)
    for i in range(0, 4096, 12):
        print("  " + ",".join("0x%04x" % v for v in px[i:i + 12]) + ",")
    print("};\n")
print("#endif")
