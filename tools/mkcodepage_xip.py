#!/usr/bin/env python3
"""Embed the normal Rockbox codepage generator's output as read-only tables."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile


def generate(generator, output):
    lines = ["/* Generated by mkcodepage_xip.py; do not edit. */",
             "#include <stdint.h>"]
    with tempfile.TemporaryDirectory(dir=output.parent, prefix="codepages-") as tmp:
        subprocess.run([str(generator.resolve())], cwd=tmp, check=True)
        for name, size in [("iso", 9 * 128 * 2),
                           ("932", 65536), ("936", 65536),
                           ("949", 65536), ("950", 65536)]:
            data = (Path(tmp) / (name + ".cp")).read_bytes()
            if len(data) != size:
                raise ValueError(f"Unexpected {name}.cp size: {len(data)}")
            values = struct.unpack("<" + "H" * (len(data) // 2), data)
            lines.append(f"static const uint16_t codepage_xip_{name}[{len(values)+1}] = {{")
            for i in range(0, len(values), 16):
                lines.append("    " + ",".join(f"0x{x:04x}" for x in values[i:i+16]) + ",")
            lines.append("    0\n};")
    text = "\n".join(lines) + "\n"
    if not output.exists() or output.read_text() != text:
        output.write_text(text)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("generator", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.generator, args.output)
